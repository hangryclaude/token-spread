/**
 * Generate `src/render/fonts.ts` from the woff2 files in `site/assets/fonts/`.
 *
 * The audit document has to be a single file that opens offline, so its type cannot be
 * fetched — it has to be carried. Keeping the base64 in a generated module means
 * `renderAuditHtml` stays pure (no filesystem, no network) and the document stays one file.
 *
 *   bun run bench/build-fonts.ts
 *
 * Re-run this after replacing a font. The generated module is committed on purpose: a
 * build step nobody remembers to run is a build step that silently rots.
 */
import { join } from "node:path";

const FONTS = [
  { const: "PLEX_SANS_VAR", file: "plex-sans-var.woff2" },
  { const: "PLEX_MONO_400", file: "plex-mono-400.woff2" },
  { const: "PLEX_MONO_600", file: "plex-mono-600.woff2" },
];

const dir = join(import.meta.dir, "..", "site", "assets", "fonts");
const parts: string[] = [
  "// GENERATED by bench/build-fonts.ts — do not edit by hand.",
  "//",
  "// IBM Plex, SIL Open Font License 1.1. Full text: site/assets/fonts/LICENSE.txt.",
  "// Carried as base64 so the audit document is one file that opens offline, with no",
  "// request to any third party — the same promise the rest of the tool makes.",
  "",
];

let total = 0;
for (const f of FONTS) {
  const bytes = new Uint8Array(await Bun.file(join(dir, f.file)).arrayBuffer());
  if (!(bytes[0] === 0x77 && bytes[1] === 0x4f && bytes[2] === 0x46 && bytes[3] === 0x32)) {
    throw new Error(`${f.file} is not a woff2 file`);
  }
  const b64 = Buffer.from(bytes).toString("base64");
  total += b64.length;
  parts.push(`/** ${f.file} — ${bytes.length.toLocaleString()} bytes */`);
  parts.push(`export const ${f.const} = "${b64}";`, "");
}

await Bun.write(join(import.meta.dir, "..", "src", "render", "fonts.ts"), parts.join("\n"));
console.log(`wrote src/render/fonts.ts — ${total.toLocaleString()} base64 chars across ${FONTS.length} faces`);
